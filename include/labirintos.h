// Função para desenhar o mapa usando shaders
void desenhaMapa(int mapa[20][20], Shader &shader) {
  // Definir vértices de um quadrado unitário
  float vertices[] = {0.0f,          0.0f, TAMANHO_BLOCO, 0.0f, TAMANHO_BLOCO,
                      TAMANHO_BLOCO, 0.0f, TAMANHO_BLOCO};

  unsigned int indices[] = {0, 1, 2, 2, 3, 0};

  // Criar buffers
  unsigned int VBO, VAO, EBO;
  glGenVertexArrays(1, &VAO);
  glGenBuffers(1, &VBO);
  glGenBuffers(1, &EBO);

  glBindVertexArray(VAO);

  glBindBuffer(GL_ARRAY_BUFFER, VBO);
  glBufferData(GL_ARRAY_BUFFER, sizeof(vertices), vertices, GL_STATIC_DRAW);

  glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, EBO);
  glBufferData(GL_ELEMENT_ARRAY_BUFFER, sizeof(indices), indices,
               GL_STATIC_DRAW);

  glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 2 * sizeof(float), (void *)0);
  glEnableVertexAttribArray(0);

  shader.use();
  shader.setVec3("color", 0.5f, 0.5f, 0.5f); // Cor cinza para paredes

  for (int i = 0; i < 20; i++) {
    for (int j = 0; j < 20; j++) {
      if (mapa[i][j] == 1) {
        float x = j * TAMANHO_BLOCO;
        float y = i * TAMANHO_BLOCO;
        shader.setVec3("color", 0.5f, 0.5f, 0.5f); // Cor cinza para paredes
        shader.setVec2("offset", x, y);
        glDrawElements(GL_TRIANGLES, 6, GL_UNSIGNED_INT, 0);
      } else if (mapa[i][j] == 2) {
        float x = j * TAMANHO_BLOCO;
        float y = i * TAMANHO_BLOCO;
        shader.setVec3("color", 0.0f, 1.0f, 0.0f); // Cor verde para saída
        shader.setVec2("offset", x, y);
        glDrawElements(GL_TRIANGLES, 6, GL_UNSIGNED_INT, 0);
      }
    }
  }

  glDeleteVertexArrays(1, &VAO);
  glDeleteBuffers(1, &VBO);
  glDeleteBuffers(1, &EBO);
}

// Função para verificar colisão
bool verificaColisao(float x, float y, int mapa[20][20]) {
  int gridX = (int)(x / TAMANHO_BLOCO);
  int gridY = (int)(y / TAMANHO_BLOCO);

  if (gridX < 0 || gridX >= 20 || gridY < 0 || gridY >= 20) {
    return true; // Fora dos limites
  }

  return mapa[gridY][gridX] == 1;
}

